export function PixelIcon({ name, size = 16, color = 'currentColor', className, style }) {
  const grid = ICONS[name];
  if (!grid) return null;

  /* Merge horizontal runs into single rects so a sprite is ~8 nodes, not 64. */
  const rects = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '1') {
        let w = 1;
        while (row[x + w] === '1') w++;
        rects.push(<rect key={y + '-' + x} x={x} y={y} width={w} height="1" />);
        x += w;
      } else {
        x++;
      }
    }
  });

  /* fill goes through `style`, not the presentation attribute, so callers can
     hand in a theme token: color="var(--ink)". */
  return (
    <svg
      viewBox="0 0 8 8"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      className={className}
      style={{ fill: color, ...style }}
      aria-hidden="true"
      focusable="false"
    >
      {rects}
    </svg>
  );
}

export default PixelIcon;
